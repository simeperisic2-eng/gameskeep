import type { NormalizedGame } from './types';

/**
 * Local mock game catalog (SPEC I2 §2) — a broad, realistic dataset used by the
 * MockProvider in DEMO mode. NO network is ever touched: this bundled data IS
 * the "external source" in demo. In production the LiveProvider (IGDB→RAWG)
 * replaces it (BLUEPRINT 1.6); nothing else changes.
 *
 * ⚠️  MOCK / SEED DATA. Titles and metadata are real-world-style for a believable
 * demo, but release dates and several fields are approximate seed values — not a
 * source of truth. ~200 games spanning genres, platforms, years (1998–2027) and
 * every status, including Upcoming (future release) for the Upcoming view (I5).
 *
 * A handful are flagged `seed: false`: the provider can resolve them but they are
 * NOT pre-loaded into the DB, so the auto-resolve → auto-create path (the one I3
 * will use) is demonstrable distinct from a plain DB hit (SPEC I2 verify #5).
 */
export interface MockGameRecord extends NormalizedGame {
  /** false = resolvable via the provider but not bulk-seeded. Default true. */
  seed?: boolean;
}

