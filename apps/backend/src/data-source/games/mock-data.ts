/** Compact builder for a released catalog entry; override anything via `extra`. */
function mk(
  name: string,
  year: number,
  developer: string,
  publisher: string,
  genres: string[],
  platforms: string[],
  extra: Partial<MockGameRecord> = {},
): MockGameRecord {
  const slug = extra.slug ?? slugify(name);
  return {
    externalId: slug,
    name,
    slug,
    status: 'released',
    releaseDate: `${year}-03-15`,
    developer,
    publisher,
    genres,
    platforms,
    externalRefs: { mock: slug },
    ...extra,
  };
}

